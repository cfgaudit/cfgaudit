func TestRun_Allow(t *testing.T) {
	for _, tc := range []struct {
		name, allow string
		first, last int
		code        int
		want        string
	}{
		{"function", "p/p.go excepted # glue\n", 14, 16, 0, "no executable"},
		{"method", "# the only one\n\np/p.go T.method # glue\n", 20, 22, 0, "no executable"},
		{"another function still counts", "p/p.go excepted # glue\n", 9, 11, 1, "p/p.go:9-11"},
		{"no reason", "p/p.go excepted\n", 14, 16, 2, `want "path function # reason"`},
		{"empty reason", "p/p.go excepted #  \n", 14, 16, 2, `want "path function # reason"`},
		{"no such function", "p/p.go gone # glue\n", 14, 16, 2, "has no function gone"},
		{"no such file", "p/q.go gone # glue\n", 14, 16, 2, "q.go"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := setup(t)
			write(t, dir, "allow.txt", tc.allow)
			code, out := runCheck(t, dir, hunk(tc.first, tc.last), "-allow", "allow.txt", "-slack", "0")
			if code != tc.code || !strings.Contains(out, tc.want) {
				t.Errorf("exit %d, want %d and %q:\n%s", code, tc.code, tc.want, out)
			}
		})
	}
	dir := setup(t)
	if code, _ := runCheck(t, dir, hunk(3, 5), "-allow", "none.txt"); code != 2 {
		t.Errorf("missing allow file: exit %d, want 2", code)
	}
}

