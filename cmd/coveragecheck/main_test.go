func TestParseDiff(t *testing.T) {
	text := strings.Join([]string{
		"diff --git a/x.go b/x.go",
		"--- a/x.go",
		"+++ b/x.go",
		"@@ -1 +1 @@",
		"-old",
		`\ No newline at end of file`,
		"+++ looks like a header",
		"@@ -5,2 +6,0 @@",
		"-a",
		"-b",
		"@@ -9,0 +9,2 @@ func f() {",
		"+@@ -1 +1 @@",
		"+y",
		"+++ b/y.go",
		"@@ -0,0 +1 @@",
		"+z",
		"",
	}, "\n")
	got, err := parseDiff(text)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string][]int{"x.go": {1, 9, 10}, "y.go": {1}}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("got %v, want %v", got, want)
	}
	if _, err := parseDiff("@@ -1 +1 @@\n"); err == nil {
		t.Error("a hunk with no file name should be an error")
	}
}

func TestReadProfile(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "ok.out", "mode: atomic\nm/a.go:1.1,2.2 1 0\nm/a.go:1.1,2.2 1 3\nm/b.go:4.1,5.2 1 0\n")
	got, err := readProfile(filepath.Join(dir, "ok.out"), "m")
	if err != nil {
		t.Fatal(err)
	}
	want := map[string][]block{"a.go": {{1, 2, 3}}, "b.go": {{4, 5, 0}}}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("got %v, want %v", got, want)
	}
	for name, text := range map[string]string{
		"nomode.out": "m/a.go:1.1,2.2 1 0\n",
		"bad.out":    "mode: set\nnonsense\n",
	} {
		write(t, dir, name, text)
		if _, err := readProfile(filepath.Join(dir, name), "m"); err == nil {
			t.Errorf("%s: expected an error", name)
		}
	}
}

