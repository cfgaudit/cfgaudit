const testModule = "module example.invalid/m\n\ngo 1.24\n"

const testSource = `package p

func covered() int {
	return 1
}

func missed(x int) int {
	if x > 0 {
		return 1
	}
	return 2
}

func excepted() int {
	return 3
}

type T struct{}

func (t *T) method() int {
	return 4
}
`

// testProfile has covered ran, missed ran up to its if without taking it, and
// excepted and method never ran. Line 10 is hit by nothing.
const testProfile = `mode: set
example.invalid/m/p/p.go:3.20,5.2 1 1
example.invalid/m/p/p.go:7.24,8.11 1 1
example.invalid/m/p/p.go:8.11,10.3 1 0
example.invalid/m/p/p.go:11.2,11.10 1 0
example.invalid/m/p/p.go:14.22,16.2 1 0
example.invalid/m/p/p.go:20.27,22.2 1 0
`

// setup writes a module with one source file and a profile.
func setup(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	write(t, dir, "go.mod", testModule)
	write(t, dir, "p/p.go", testSource)
	write(t, dir, "coverage.out", testProfile)
	return dir
}

func write(t *testing.T, dir, name, text string) {
	t.Helper()
	p := filepath.Join(dir, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(text), 0o600); err != nil {
		t.Fatal(err)
	}
}

// hunk builds a diff that adds lines first to last of p/p.go.
func hunk(first, last int) differ {
	n := last - first + 1
	head := "--- a/p/p.go\n+++ b/p/p.go\n@@ -0,0 +" + strconv.Itoa(first) + "," + strconv.Itoa(n) + " @@\n"
	return func(string, string) (string, error) {
		return head + strings.Repeat("+x\n", n), nil
	}
}

func runCheck(t *testing.T, dir string, diff differ, args ...string) (int, string) {
	t.Helper()
	var out, errb bytes.Buffer
	code := run(args, dir, diff, &out, &errb)
	return code, out.String() + errb.String()
}

func TestRun(t *testing.T) {
	for _, tc := range []struct {
		name  string
		diff  differ
		args  []string
		code  int
		wants []string
	}{
		{"covered lines pass", hunk(3, 5), nil, 0, []string{"3 of 3 changed lines covered, 100.0%"}},
		{"no executable line", hunk(1, 2), nil, 0, []string{"no executable lines changed"}},
		{"uncovered within the slack", hunk(9, 11), nil, 0, []string{"0 of 3", "p/p.go:9-11"}},
		{"uncovered over the slack", hunk(9, 11), []string{"-slack", "1"}, 1, []string{"0.0%", "p/p.go:9-11"}},
		{"percentage passes over the slack", hunk(3, 11), []string{"-slack", "0", "-min", "50"}, 0, []string{"p/p.go:9-11"}},
		{"line of an untaken if is covered", hunk(8, 8), []string{"-slack", "0"}, 0, []string{"1 of 1"}},
		{"bad flag", hunk(3, 5), []string{"-nope"}, 2, []string{"flag provided but not defined"}},
		{"missing profile", hunk(3, 5), []string{"-profile", "none.out"}, 2, []string{"none.out"}},
		{"diff fails", func(string, string) (string, error) { return "", errors.New("no base") }, nil, 2, []string{"no base"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			code, out := runCheck(t, setup(t), tc.diff, tc.args...)
			if code != tc.code {
				t.Errorf("exit %d, want %d\n%s", code, tc.code, out)
			}
			for _, w := range tc.wants {
				if !strings.Contains(out, w) {
					t.Errorf("output lacks %q:\n%s", w, out)
				}
			}
		})
	}
}

func TestRun_FileOutsideProfileIsIgnored(t *testing.T) {
	diff := func(string, string) (string, error) {
		return "+++ b/other/x.go\n@@ -0,0 +1,3 @@\n+a\n+b\n+c\n", nil
	}
	if code, out := runCheck(t, setup(t), diff, "-slack", "0"); code != 0 || !strings.Contains(out, "no executable") {
		t.Errorf("exit %d:\n%s", code, out)
	}
}

