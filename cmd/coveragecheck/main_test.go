func TestGitDiff(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("no git")
	}
	dir := t.TempDir()
	gitRun := func(args ...string) {
		t.Helper()
		cmd := exec.Command("git", append([]string{"-c", "user.name=t", "-c", "user.email=t@example.invalid"}, args...)...) //nolint:gosec // G204: fixed arguments of this test
		cmd.Dir = dir
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	gitRun("init", "-q")
	write(t, dir, "a.go", "package a\n")
	write(t, dir, "gone.go", "package a\n")
	gitRun("add", ".")
	gitRun("commit", "-qm", "base")
	gitRun("tag", "base")
	write(t, dir, "a.go", "package a\n\nvar x = 1\n") // not committed: it still counts
	write(t, dir, "notes.txt", "not go\n")
	if err := os.Remove(filepath.Join(dir, "gone.go")); err != nil {
		t.Fatal(err)
	}
	text, err := gitDiff(dir, "base")
	if err != nil {
		t.Fatal(err)
	}
	got, err := parseDiff(text)
	if err != nil {
		t.Fatal(err)
	}
	if want := map[string][]int{"a.go": {2, 3}}; !reflect.DeepEqual(got, want) {
		t.Errorf("got %v, want %v\n%s", got, want, text)
	}
	if _, err := gitDiff(dir, "nosuchref"); err == nil {
		t.Error("expected an error for an unknown base")
	}
}
